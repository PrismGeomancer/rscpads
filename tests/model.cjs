// Dependency-free checks for money, persistence, isolation and error paths.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {webcrypto}=require('node:crypto');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const saved=new Map();
let failStorage=false;
function load(){const ctx=vm.createContext({console,crypto:webcrypto,localStorage:{getItem:k=>saved.get(k)||null,setItem:(k,v)=>{if(failStorage)throw new Error('quota');saved.set(k,v);}},window:null});ctx.window=ctx;for(const file of ['rescues.js','data.js'])vm.runInContext(fs.readFileSync(path.join(root,'js',file),'utf8'),ctx);return ctx;}
let ctx=load(),rp=ctx.RP;
assert.equal(rp.totals().tokens,12);
assert.equal(rp.totals().cents,62000);
assert.equal(rp.totals().rescues,8);
assert.ok(rp.totals().trades>=350&&rp.totals().trades<=700);
assert.equal(ctx.RESCUES.reduce((n,r)=>n+rp.rescueStats(r.id).cents,0),rp.totals().cents);
assert.ok(ctx.RESCUES.every(r=>r.status==='listed'&&r.url.startsWith('https://')));
assert.equal(rp.allocationMilestones(0).nextCents,10000);
assert.equal(rp.allocationMilestones(9999).completed,0);
assert.equal(rp.allocationMilestones(9999).progress,99);
assert.equal(rp.allocationMilestones(10000).nextCents,25000);
assert.equal(rp.allocationMilestones(25000).completed,2);
assert.equal(rp.allocationMilestones(50000).nextCents,null);
assert.equal(rp.allocationMilestones(50100).progress,100);
assert.equal(rp.userRescueSupport().length,0);
assert.throws(()=>rp.trade('biscuit','buy',.1),/Connect/);
rp.change(s=>{s.wallet={address:'DemoTestWallet',provider:'Phantom'};s.accounts.DemoTestWallet={balance:5,holdings:{},history:[],launches:[]};});
const before=rp.token('biscuit').rescueCents;
const rBefore=rp.rescueStats('paws').cents;
const mcBefore=rp.token('biscuit').mc;
const buy=rp.trade('biscuit','buy',.5);
assert.equal(buy.feeCents,35);
assert.equal(rp.account().balance,4.5);
assert.ok(rp.account().holdings.biscuit>0);
assert.ok(rp.token('biscuit').mc>mcBefore);
assert.equal(rp.token('biscuit').rescueCents,before+35);
assert.equal(rp.rescueStats('paws').cents,rBefore+35);
const holdingsBefore=rp.account().holdings.biscuit;
const sell=rp.trade('biscuit','sell',.1);
assert.equal(sell.feeCents,7);
assert.equal(rp.account().balance,4.599);
assert.ok(rp.account().holdings.biscuit<holdingsBefore);
assert.equal(rp.rescueStats('paws').cents,rBefore+42);
const safe=JSON.stringify(rp.state);
for(const invalid of [0,-1,NaN,Infinity,1001])assert.throws(()=>rp.trade('biscuit','buy',invalid));
assert.throws(()=>rp.trade('biscuit','buy',6),/Not enough/);
assert.throws(()=>rp.trade('biscuit','sell',10),/Not enough/);
assert.throws(()=>rp.trade('biscuit','wrong',.1));
assert.equal(JSON.stringify(rp.state),safe);
failStorage=true;
assert.throws(()=>rp.trade('biscuit','buy',.1),/database/);
assert.equal(JSON.stringify(rp.state),safe,'failed persistence must roll back trade');
failStorage=false;
const image='data:image/webp;base64,TEST';
const created=rp.createToken({name:'Test dog',ticker:'TESTDOG',description:'Test description',rescueId:'scars',image});
assert.equal(created.owner,'DemoTestWallet');
assert.equal(created.rescueCents,0);
assert.equal(rp.account().launches[0].tokenId,created.id);
assert.equal(rp.rescueStats('scars').tokens,3);
const support=rp.userRescueSupport();
assert.equal(support.length,2);
assert.equal(support.find(r=>r.rescueId==='paws').cents,42);
assert.equal(support.find(r=>r.rescueId==='scars').cents,0);
assert.equal(support.find(r=>r.rescueId==='scars').launchedIds[0],created.id);
assert.equal(support.find(r=>r.rescueId==='paws').tokenIds.length,1);
assert.throws(()=>rp.createToken({name:'Another',ticker:'TESTDOG',description:'Another',rescueId:'paws'}),/already/);
ctx=load();rp=ctx.RP;
assert.equal(rp.state.wallet.address,'DemoTestWallet');
assert.equal(rp.token(created.id).image,image);
assert.equal(rp.account().history.length,2);
assert.equal(rp.account().balance,4.599);
rp.change(s=>{s.wallet=null;});
assert.equal(rp.state.accounts.DemoTestWallet.balance,4.599);
assert.throws(()=>rp.trade('biscuit','buy',.1),/Connect/);
rp.reset();
assert.equal(rp.totals().cents,62000);
assert.equal(rp.totals().tokens,12);
assert.equal(rp.state.wallet,null);
assert.equal(Object.keys(rp.state.accounts).length,0);
assert.equal(rp.userRescueSupport().length,0);
// Fees from trading your own meme must not be counted a second time.
rp.change(s=>{s.wallet={address:'Owner',provider:'Phantom'};s.accounts.Owner={balance:5,holdings:{},history:[],launches:[]};});
const own=rp.createToken({name:'Owner dog',ticker:'OWNERDOG',description:'A dog',rescueId:'paws'});
rp.trade(own.id,'buy',.5);
rp.change(()=>rp.market(own,'buy',.25));
rp.trade('biscuit','buy',.1);
const personal=rp.userRescueSupport();
assert.equal(personal.length,1);
assert.equal(personal[0].cents,own.rescueCents+7);
assert.equal(personal[0].tokenIds.length,2);
ctx=load();rp=ctx.RP;
assert.equal(rp.userRescueSupport()[0].cents,personal[0].cents);
rp.reset();
console.log('PASS: initial consistency, buy/sell accounting, rejected trades, storage rollback, launch ownership, persistence, disconnect and reset.');
console.log('PASS: milestone boundaries and completion, grouped rescue support, ownership double-count protection and persistence.');
